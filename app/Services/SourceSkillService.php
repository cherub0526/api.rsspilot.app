/**
 * 頻道 Skill：把一個來源的共用摘要萃取成 Agent Skill（SKILL.md + references/videos.md）。
 *
 * 模型只負責 body 的內容。frontmatter、開頭的第三方聲明、MCP 段落與影片清單一律由這裡
 * 用系統模板組出：skill 全站共用，任何讓模型決定的結構都可能被影片內容注入，影響所有
 * 安裝它的使用者（spec SR-1～SR-3、SR-8）。
 */
class SourceSkillService
{
    public const NAME_PREFIX = 'rsspilot-';

