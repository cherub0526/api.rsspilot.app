    /** 取材的影片數（spec S15）。 */
    private const SAMPLE_SIZE = 30;

    /** 輸出上限；SKILL.md 本身也只有 50,000 字元（SR-7）。 */
    private const MAX_TOKENS = 8000;

    /** 一次送數十支影片的摘要、要一整份 SKILL.md 回來，60 秒的預設等不到；要小於 worker 的 --timeout。 */
    private const TIMEOUT_SECONDS = 240;

    public function __construct(private Sanitizer $sanitizer, private SummarySampler $sampler)
    {
    }

    /**
     * 取材、組 prompt、呼叫 LLM，回傳模型的原始輸出；組裝與清洗交給 assemble()。
     *
     * skill 全站共用，不帶使用者建構 manager：只吃用途層的模型路由，不讓觸發者的方案
     * 決定所有人拿到的品質。
     */
    public function generateRaw(Source $source, string $language): string
    {
        // 語言名稱會進 system prompt，查不到就不能把呼叫端給的字串原樣放進去
        $name = ISO6391::getNameByCode(ISO6391::normalize($language));
        if (!is_string($name)) {
            throw new InvalidArgumentException("Unsupported skill language: {$language}");
        }

        [$channel] = $this->sanitizer->inline((string) $source->getAttribute('title'));
        $template = new ChannelSkillTemplate([
            'language' => $name,
            'channel'  => mb_substr($channel, 0, self::CHANNEL_TITLE_MAX_LENGTH),
        ]);

        $samples = array_map(
            fn (array $sample) => $this->sampleText($sample['media'], $sample['summary']),
            $this->sampler->sample($source, $language, self::SAMPLE_SIZE)
        );

        return (new TemplateCompletionManager(Completion::make(), $template))
            ->setOptions(['max_tokens' => self::MAX_TOKENS])
            ->setTimeout(self::TIMEOUT_SECONDS)
            ->completeAndGetContent($template->wrap(implode("\n\n", $samples)));
    }

    /** 一支影片一段：標題與日期當小標，內容沿用心智圖的輸入組法。 */
    private function sampleText(Media $media, Summary $summary): string
    {
        $date = $this->date($media->getAttribute('published_at'));

        return '### ' . $media->getAttribute('title') . ($date !== null ? " ({$date})" : '')
            . "\n\n" . $summary->aiInput();
    }

    /**
     * `rsspilot-<slug>-<source id 末 6 碼>`；標題轉不出 ASCII（中文、日文頻道）時
     * 退回 `rsspilot-<source id 末 10 碼>`。`Source.metadata` 沒有 YouTube 的 customUrl，
     * 只能用標題。
     *
     * id 片段讓同名頻道不會裝進同一個資料夾互相覆蓋；name 只看來源不看語言，
     * 同一頻道換語言重裝時才會覆蓋同一份。
     */
    public function skillName(Source $source): string
    {
        $id = strtolower((string) $source->getKey());
        $slug = $this->slug((string) $source->getAttribute('title'));

        return $slug === ''
            ? self::NAME_PREFIX . substr($id, -10)
            : self::NAME_PREFIX . $slug . '-' . substr($id, -6);
    }

    /** SKILL.md body 開頭的系統聲明（SR-7）。 */
    public function disclaimer(string $language): string
    {
        return $this->text($language, 'disclaimer');
    }

    /**
     * 把模型輸出組成完整的 skill。
     *
     * @param Media[] $media 取材的影片，順序即 references/videos.md 的順序
     * @return array{name: string, description: string, content: string, references: string, outline: list<string>, sanitized_rules: list<string>}
     */
    public function assemble(Source $source, string $language, string $llmOutput, array $media): array
    {
        [$topics, $llmOutput] = $this->extractTopics($llmOutput);
        [$body, $rules] = $this->sanitizer->body($llmOutput);
        [$titleRules, $references] = $this->references($language, $media);

        $name = $this->skillName($source);
        $description = $this->description($source, $language, $topics, $this->outline($body));

        $head = "---\nname: {$name}\ndescription: " . $this->yamlString($description) . "\n---\n\n"
            . $this->disclaimer($language) . "\n\n";
        $tail = "\n\n" . $this->mcpSection($language) . "\n";

        [$body, $truncated] = $this->truncateBody($body, $this->contentLimit() - mb_strlen($head . $tail));
        if ($truncated) {
            // 截斷可能切開原本被成對規則包住的結構，對最後的文字再清洗一次
            [$body, $again] = $this->sanitizer->body($body);
            $rules = array_merge($rules, $again);
        }
        // 模型自己留下沒關的 fence 也一樣：不關的話後面的系統段落會被吞進 code block
        $body = $this->closeFence($body);
        if ($truncated) {
            $body .= "\n\n" . self::TRUNCATED_NOTICE;
        }

        return [
            'name'            => $name,
            'description'     => $description,
            'content'         => $head . $body . $tail,
            'references'      => $references,
            'outline'         => $this->outline($body),
            'sanitized_rules' => array_values(array_unique(array_merge($rules, $titleRules))),
        ];
    }

    private function slug(string $title): string
    {
        $slug = Str::slug($title);

        // 拿掉保留字可能讓兩側接起來又拼出保留字（cl-claude-aude），所以重複到穩定為止
        do {
            $before = $slug;
            $slug = str_replace(self::RESERVED_WORDS, '', $slug);
        } while ($slug !== $before);

        $slug = (string) preg_replace('/-+/', '-', $slug);

        return trim(substr($slug, 0, self::SLUG_MAX_LENGTH), '-');
    }

    private function text(string $language, string $key): string
    {
        return (self::TEXT[$language] ?? self::TEXT['en'])[$key];
    }

    /**
     * @return array{0: list<string>, 1: string} [主題關鍵字, 拿掉 TOPICS 行之後的輸出]
     */
    private function extractTopics(string $llmOutput): array
    {
        $topics = [];
        $pattern = '/^[ \t]*' . preg_quote(self::TOPICS_PREFIX, '/') . '(.*)$/mi';

        if (preg_match($pattern, $llmOutput, $m)) {
            foreach (preg_split('/[,，、;；]/u', $m[1]) ?: [] as $topic) {
                [$topic] = $this->sanitizer->inline($topic);
                $topic = trim((string) preg_replace('/[^\p{L}\p{N}\s&+.\'-]/u', '', $topic));
                if ($topic !== '' && !$this->isBroadTopic($topic)) {
                    $topics[] = mb_substr($topic, 0, self::TOPIC_MAX_LENGTH);
                }
            }
        }

        return [
            array_slice(array_values(array_unique($topics)), 0, self::TOPICS_MAX_ITEMS),
            (string) preg_replace($pattern, '', $llmOutput),
        ];
    }

    /**
     * 主題會進 description、決定 agent 何時自動載入 skill。「任何問題」「every task」這種
     * 寫法等於讓 skill 在所有對話都被載入，只收短的具體主題。
     */
    private function isBroadTopic(string $topic): bool
    {
        if (preg_match(self::BROAD_TOPIC_PATTERN, $topic)) {
            return true;
        }

        return preg_match('/\p{Han}|\p{Hiragana}|\p{Katakana}|\p{Hangul}/u', $topic)
            ? mb_strlen($topic) > self::TOPIC_MAX_CJK_CHARS
            : count(preg_split('/\s+/', $topic) ?: []) > self::TOPIC_MAX_WORDS;
    }

    /**
     * description 決定 agent 什麼時候自動載入 skill，所以由系統模板組成，模型只能填主題
     * 關鍵字（SR-3）。沒給主題時用 outline 頂替。
     *
     * @param list<string> $topics
     * @param list<string> $outline
     */
    private function description(Source $source, string $language, array $topics, array $outline): string
    {
        [$channel] = $this->sanitizer->inline((string) $source->getAttribute('title'));
        $channel = mb_substr(str_replace(['"', '「', '」'], '', $channel), 0, self::CHANNEL_TITLE_MAX_LENGTH);

        $topics = $topics !== [] ? $topics : array_slice($outline, 0, 5);
        $separator = in_array($language, ['zh-TW', 'zh-CN'], true) ? '、' : ', ';
        $about = $topics !== [] ? implode($separator, $topics) : $this->text($language, 'topics');

        return mb_substr(
            sprintf($this->text($language, 'description'), $channel, $about),
            0,
            self::DESCRIPTION_MAX_LENGTH
        );
    }

    /**
     * 雙引號字串：JSON 字串是合法的 YAML 雙引號純量，換行、引號、控制字元都會被跳脫，
     * 不必自己處理 YAML 的指示字元。
     */
    private function yamlString(string $value): string
    {
        return (string) json_encode($value, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    }

    private function mcpSection(string $language): string
    {
        return implode("\n", [
            $this->text($language, 'mcp_heading'),
            '',
            $this->text($language, 'mcp_intro'),
            '',
            '- ' . sprintf($this->text($language, 'mcp_url'), (string) config('skills.mcp_url')),
            '- ' . $this->text($language, 'mcp_header'),
            '- ' . $this->text($language, 'mcp_key'),
            '',
            $this->text($language, 'references'),
        ]);
    }

    /**
     * 一支影片一行：日期、標題、由 video id 組出的連結。標題是頻道主控制的不可信文字，
     * 去掉換行與 markdown 結構字元，讓它不能組成連結、HTML 或指令（SR-2）。
     *
     * @param Media[] $media
     * @return array{0: list<string>, 1: string} [觸發的清洗規則, references/videos.md 全文]
     */
    private function references(string $language, array $media): array
    {
        $rules = [];
        $head = $this->text($language, 'videos') . "\n\n";
        $notice = "\n\n" . self::TRUNCATED_NOTICE . "\n";
        $limit = (int) config('skills.limits.references');

        $text = $head;
        foreach ($media as $item) {
            $id = $this->videoId((string) $item->getAttribute('resource_id'));
            if ($id === null) {
                continue;
            }

            [$title, $titleRules] = $this->sanitizer->inline((string) $item->getAttribute('title'));
            $rules = array_merge($rules, $titleRules);

            $date = $this->date($item->getAttribute('published_at'));
            $line = '- ' . ($date !== null ? $date . ' — ' : '')
                . $this->escapeTitle($title) . ' — ' . self::YOUTUBE_WATCH_URL . $id . "\n";

            if (mb_strlen($text . $line . $notice) > $limit) {
                return [$rules, rtrim($text) . $notice];
            }
            $text .= $line;
        }

        return [$rules, $text];
    }

    private function escapeTitle(string $title): string
    {
        $title = strtr($title, ['[' => '［', ']' => '］', '`' => "'", '<' => '‹', '>' => '›']);
        $title = (string) preg_replace('/([\\\*_~|#!(){}])/', '\\\$1', $title);
        $title = mb_substr($title, 0, (int) config('skills.limits.title'));

        // 截在跳脫的反斜線後面會把下一個字元（分隔符號）吃掉
        return rtrim($title, '\\');
    }

    /** media.published_at 沒有 datetime cast，讀出來是字串。 */
    private function date(mixed $value): ?string
    {
        if ($value === null || $value === '') {
            return null;
        }

        try {
            return Carbon::parse($value)->format('Y-m-d');
        } catch (Throwable) {
            return null;
        }
    }

    /** media.resource_id 帶 `yt:video:` 前綴（docs/lore/media/pitfalls.md）。 */
    private function videoId(string $resourceId): ?string
    {
        $id = (string) preg_replace('/^yt:video:/', '', $resourceId);

        return preg_match('/^[A-Za-z0-9_-]{6,20}$/', $id) ? $id : null;
    }

    private function contentLimit(): int
    {
        return (int) config('skills.limits.content');
    }

    /**
     * 在最後一個放得下的完整 `##` 段落之後截斷；連第一段都放不下時才在行邊界硬切。
     *
     * @return array{0: string, 1: bool} [body, 是否截斷]
     */
    private function truncateBody(string $body, int $budget): array
    {
        if (mb_strlen($body) <= $budget) {
            return [$body, false];
        }

        $budget -= mb_strlen("\n\n" . self::TRUNCATED_NOTICE) + self::FENCE_RESERVE;

        $kept = '';
        foreach ($this->sections($body) as $section) {
            if (mb_strlen($kept . $section) > $budget) {
                break;
            }
            $kept .= $section;
        }

        if (trim($kept) === '') {
            $kept = mb_substr($body, 0, max(0, $budget));
            $cut = mb_strrpos($kept, "\n");
            $kept = $cut === false ? $kept : mb_substr($kept, 0, $cut);
        }

        return [rtrim($kept), true];
    }

    /**
     * 依 code fence 外的 `## ` 行切段。每段含結尾換行，串起來等於原文。
     *
     * @return list<string>
     */
    private function sections(string $body): array
    {
        $sections = [];
        $current = '';
        $fence = null;

        foreach (explode("\n", $body) as $line) {
            $wasOpen = $fence !== null;
            $fence = $this->fenceAfter($fence, $line);
            if (!$wasOpen && $fence === null && str_starts_with($line, '## ') && $current !== '') {
                $sections[] = $current;
                $current = '';
            }
            $current .= $line . "\n";
        }
        $sections[] = $current;

        return $sections;
    }

    /** body 結尾還在 code block 裡就補上同樣的 fence，否則截斷標記與 MCP 段落會被吞進去。 */
    private function closeFence(string $body): string
    {
        $fence = null;
        foreach (explode("\n", $body) as $line) {
            $fence = $this->fenceAfter($fence, $line);
        }

        return $fence === null ? $body : $body . "\n" . $fence;
    }

    /**
     * 讀完這一行之後所在的 fence（null 表示不在 code block 裡）。CommonMark：開頭可以是
     * 3 個以上的反引號或波浪號，只有同種字元、長度不短於開頭、後面沒有其他字的行才關得起來。
     */
    private function fenceAfter(?string $fence, string $line): ?string
    {
        if ($fence === null) {
            return preg_match('/^[ \t]*(`{3,}|~{3,})/', $line, $m) ? $m[1] : null;
        }

        $closes = preg_match('/^[ \t]*' . preg_quote($fence[0], '/') . '{' . strlen($fence) . ',}[ \t]*$/', $line);

        return $closes ? null : $fence;
    }

    /**
     * 只取 `##` 標題、轉成純文字。outline 會出現在免費使用者的上鎖畫面，抽得太細等於
     * 洩漏內文（SR-6）。
     *
     * @return list<string>
     */
    private function outline(string $body): array
    {
        $items = [];
        $fence = null;

        foreach (explode("\n", $body) as $line) {
            $wasOpen = $fence !== null;
            $fence = $this->fenceAfter($fence, $line);
            if ($wasOpen || $fence !== null || !preg_match('/^##[ \t]+(.+)$/', $line, $m)) {
                continue;
            }

            $item = $this->plainText($m[1]);
            if ($item !== '') {
                $items[] = $item;
            }
            if (count($items) >= self::OUTLINE_MAX_ITEMS) {
                break;
            }
        }

        return $items;
    }

    private function plainText(string $markdown): string
    {
        $text = (string) preg_replace('/!?\[([^\]]*)\]\([^)]*\)/', '$1', $markdown);
        $text = (string) preg_replace('/\b(?:https?:\/\/|www\.)\S+/i', '', $text);
        $text = (string) preg_replace('/[*`\[\]#<>_~]/', '', $text);
        $text = trim((string) preg_replace('/\s+/u', ' ', $text));

        return trim(mb_substr($text, 0, self::OUTLINE_ITEM_MAX_LENGTH));
    }
}
