    public const TRUNCATED_NOTICE = '（內容已截斷）';

    /** 模型可以在輸出第一段放一行 `TOPICS: a, b, c`，這是它唯一能影響 description 的地方。 */
    public const TOPICS_PREFIX = 'TOPICS:';

    public const DESCRIPTION_MAX_LENGTH = 1024;

    public const OUTLINE_MAX_ITEMS = 15;

    public const OUTLINE_ITEM_MAX_LENGTH = 80;

    /** 標題轉出來的 slug 上限；加上前綴與 id 片段後仍在 Agent Skill 的 64 字元內。 */
    private const SLUG_MAX_LENGTH = 40;

    /** Agent Skill 規格不允許 name 含這些字。 */
    private const RESERVED_WORDS = ['claude', 'anthropic'];

    private const TOPICS_MAX_ITEMS = 8;

    private const TOPIC_MAX_LENGTH = 40;

    private const TOPIC_MAX_WORDS = 4;

    private const TOPIC_MAX_CJK_CHARS = 12;

    private const BROAD_TOPIC_PATTERN = '/\b(?:any|all|every|always|anything|everything)\b|任何|所有|每次|一切/iu';

